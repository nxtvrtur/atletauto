/** Полный план тем. Слаги уникальны по построению. */
export function plan() {
  const out = [];
  for (const [citySlug, cityAcc, cityNom, note] of CITIES) {
    for (const [slugT, titleT, brief] of CITY_INTENTS) {
      out.push({
        slug: slugT.replace('%s', citySlug),
        // «в Москву», но «Владивосток — Москва»: падеж зависит от шаблона
        title: titleT.replace('%s', titleT.startsWith('Доставка') ? cityAcc : cityNom),
        brief: `Направление: ${note}. Фокус статьи — ${brief}.`,
        cluster: 'cities',
      });
    }
  }
  for (const [cluster, list] of Object.entries(CLUSTERS)) {
    for (const [slug, title] of list) out.push({ slug, title, brief: '', cluster });
  }
  return out;
}
